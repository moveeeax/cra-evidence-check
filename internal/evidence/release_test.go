func TestFindFilesHonoursExcludes(t *testing.T) {
	root := filepath.Join("..", "..", "testdata", "repo", "compliant")
	got, err := FindFiles(root, []string{"package.json", "go.mod"}, DefaultExcludes)
	if err != nil {
		t.Fatalf("FindFiles: %v", err)
	}
	want := map[string]bool{"go.mod": true, "ui/package.json": true}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for _, g := range got {
		if !want[g] {
			t.Errorf("unexpected match %q", g)
		}
	}

	// Excluding "ui" must drop the nested manifest.
	got, err = FindFiles(root, []string{"package.json", "go.mod"}, append(DefaultExcludes, "ui"))
	if err != nil {
		t.Fatalf("FindFiles: %v", err)
	}
	if len(got) != 1 || got[0] != "go.mod" {
		t.Errorf("got %v, want [go.mod]", got)
	}
}

func TestReportOKAndTally(t *testing.T) {
	r := Report{Results: []Result{
		{Status: StatusPass}, {Status: StatusPass}, {Status: StatusSkip},
	}}
	r.Tally()
	if r.Counts.Pass != 2 || r.Counts.Skip != 1 || r.Counts.Fail != 0 {
		t.Fatalf("counts = %+v", r.Counts)
	}
	if !r.OK() {
		t.Error("a run with only passes and skips should be OK")
	}
	r.Strict = true
	if r.OK() {
		t.Error("--strict must turn a skip into a failing run")
	}
	r.Results = append(r.Results, Result{Status: StatusFail})
	r.Strict = false
	r.Tally()
	if r.OK() {
		t.Error("a run with a failure is never OK")
	}
	if r.Headline() != "2 passed, 1 failed, 1 skipped" {
		t.Errorf("headline = %q", r.Headline())
	}
}
