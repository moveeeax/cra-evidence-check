func TestClassifyFile(t *testing.T) {
	cases := map[string]Kind{
		"acme-gateway_1.4.0_linux_amd64.tar.gz":     KindArtifact,
		"acme-gateway_1.4.0_linux_amd64.tar.gz.sig": KindSignature,
		"acme-gateway.cdx.json":                     KindSBOM,
		"sensor-fw.spdx.json":                       KindSBOM,
		"bom.json":                                  KindSBOM,
		"my-sbom.json":                              KindSBOM,
		"firmware.spdx":                             KindSBOM,
		"checksums.txt":                             KindChecksums,
		"SHA256SUMS":                                KindChecksums,
		"app_checksums.txt":                         KindChecksums,
		"app.sha256":                                KindChecksums,
		// A signature over a manifest is a signature, not a second manifest.
		"checksums.txt.asc":            KindSignature,
		"SHA256SUMS.sig":               KindSignature,
		"app.intoto.jsonl":             KindSignature,
		"app.sigstore.json":            KindSignature,
		"release-notes.md":             KindArtifact,
		"controller_3.2.0_windows.exe": KindArtifact,
	}
	for name, want := range cases {
		if got := ClassifyFile(name); got != want {
			t.Errorf("ClassifyFile(%q) = %q, want %q", name, got, want)
		}
	}
}

func TestParseChecksums(t *testing.T) {
	in := []byte("# generated by shasum\n" +
		"3fa1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f  dist/app_linux_amd64\n" +
		"\n" +
		"AAAA1111b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d *app.exe\n")
	entries, err := ParseChecksums(in)
	if err != nil {
		t.Fatalf("ParseChecksums: %v", err)
	}
	if len(entries) != 2 {
		t.Fatalf("got %d entries, want 2", len(entries))
	}
	if entries[0].Name != "app_linux_amd64" {
		t.Errorf("name = %q, want the base name", entries[0].Name)
	}
	if entries[1].Name != "app.exe" {
		t.Errorf("name = %q, want the '*' binary marker stripped", entries[1].Name)
	}
	if entries[1].Digest != "aaaa1111b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d" {
		t.Errorf("digest = %q, want it lower-cased", entries[1].Digest)
	}
}

func TestParseChecksumsRejectsGarbage(t *testing.T) {
	for _, in := range []string{"not-a-digest  app\n", "onlyonefield\n"} {
		if _, err := ParseChecksums([]byte(in)); err == nil {
			t.Errorf("ParseChecksums(%q) should have failed", in)
		}
	}
}

func TestScanReleaseFixture(t *testing.T) {
	dir := filepath.Join("..", "..", "testdata", "release", "complete")
	rel, err := ScanRelease(dir)
	if err != nil {
		t.Fatalf("ScanRelease: %v", err)
	}
	if len(rel.Files) != 4 {
		t.Fatalf("got %d files, want 4: %+v", len(rel.Files), rel.Files)
	}
	if got := len(rel.ByKind(KindArtifact)); got != 1 {
		t.Errorf("%d artefacts, want 1", got)
	}
	if got := len(rel.ByKind(KindSBOM)); got != 1 {
		t.Errorf("%d SBOMs, want 1", got)
	}
	if got := len(rel.ByKind(KindChecksums)); got != 1 {
		t.Errorf("%d checksum manifests, want 1", got)
	}
	if got := len(rel.ByKind(KindSignature)); got != 1 {
		t.Errorf("%d signatures, want 1", got)
	}

	// The digest recomputed by the scanner must equal the one in the manifest;
	// that equality is the whole basis of CRA-06.
	manifest := rel.ByKind(KindChecksums)[0]
	data, err := ReadRepoFile(dir, manifest.Name)
	if err != nil {
		t.Fatal(err)
	}
	entries, err := ParseChecksums(data)
	if err != nil {
		t.Fatal(err)
	}
	byName := map[string]string{}
	for _, f := range rel.Files {
		byName[f.Name] = f.SHA256
	}
	for _, e := range entries {
		if byName[e.Name] != e.Digest {
			t.Errorf("%s: scanned %s, manifest %s", e.Name, byName[e.Name], e.Digest)
		}
	}
}

